    (r"利润分配|分红|送转|权益分派|派息|现金分红", "分红送转"),
    (r"减持|增持", "增减持"),
    (r"回购", "回购"),
    (r"质押|解除质押|补充质押", "股权质押"),
    (r"重组|重大资产|吸收合并|收购|出售资产|资产置换", "重组并购"),
    (r"重大合同|中标|战略合作|框架协议|签订.{0,6}协议|重大订单", "合同业务"),
    (r"立案|处罚|警示函|监管函|行政监管措施|纪律处分|诉讼|仲裁|冻结", "风险事项"),
